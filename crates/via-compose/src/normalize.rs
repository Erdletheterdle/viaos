/// Reject dangling references to services, networks and volumes.
fn validate_references(d: &Deployment) -> Result<(), Error> {
    for (name, svc) in &d.services {
        for dep in &svc.depends_on {
            if !d.services.contains_key(&dep.service) {
                return Err(Error::UnknownReference {
                    service: name.clone(),
                    kind: "service in depends_on",
                    referenced: dep.service.clone(),
                });
            }
        }
        for net in &svc.networks {
            if !d.networks.contains_key(net) {
                return Err(Error::UnknownReference {
                    service: name.clone(),
                    kind: "network",
                    referenced: net.clone(),
                });
            }
        }
        for m in &svc.mounts {
            if let Mount::Volume { source, .. } = m {
                // Anonymous volumes are synthesized here, not declared by the
                // author, so they are legitimately absent from `volumes:`.
                let anonymous = source.starts_with(&format!("{}-{}-", d.project, name));
                if !anonymous && !d.volumes.contains_key(source) {
                    return Err(Error::UnknownReference {
                        service: name.clone(),
                        kind: "volume",
                        referenced: source.clone(),
                    });
                }
            }
        }
    }
    Ok(())
}

/// `command:`/`entrypoint:` as argv.
///
/// Compose splits a string form with shell-like word rules rather than
/// wrapping it in `sh -c`, so `command: echo "a b"` is two arguments and runs
/// without a shell in the container. Getting this wrong would change what
/// actually executes, so it is not approximated with `split_whitespace`.
fn to_argv(v: &StringOrList) -> Result<Vec<String>, Error> {
    match v {
        StringOrList::Scalar(s) => shell_split(&s.as_string()),
        StringOrList::List(l) => Ok(l.iter().map(|s| s.as_string()).collect()),
    }
}

/// A plain list of values, where a lone string is one entry rather than a
/// command to be split.
fn to_string_list(v: &StringOrList) -> Vec<String> {
    match v {
        StringOrList::Scalar(s) => vec![s.as_string()],
        StringOrList::List(l) => l.iter().map(|s| s.as_string()).collect(),
    }
}

/// Split on whitespace, honoring single quotes, double quotes and backslash
/// escapes.
fn shell_split(s: &str) -> Result<Vec<String>, Error> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut has_word = false;
    let mut chars = s.chars().peekable();

    while let Some(c) = chars.next() {
        match c {
            c if c.is_whitespace() => {
                if has_word {
                    out.push(std::mem::take(&mut cur));
                    has_word = false;
                }
            }
            '\'' => {
                has_word = true;
                loop {
                    match chars.next() {
                        Some('\'') => break,
                        Some(c) => cur.push(c),
                        None => {
                            return Err(Error::UnbalancedQuote {
                                value: s.to_string(),
                            });
                        }
                    }
                }
            }
            '"' => {
                has_word = true;
                loop {
                    match chars.next() {
                        Some('"') => break,
                        Some('\\') => match chars.next() {
                            // Inside double quotes a backslash only escapes
                            // these; anything else stays literal, as in sh.
                            Some(n @ ('"' | '\\' | '$' | '`')) => cur.push(n),
                            Some(n) => {
                                cur.push('\\');
                                cur.push(n);
                            }
                            None => {
                                return Err(Error::UnbalancedQuote {
                                    value: s.to_string(),
                                });
                            }
                        },
                        Some(c) => cur.push(c),
                        None => {
                            return Err(Error::UnbalancedQuote {
                                value: s.to_string(),
                            });
                        }
                    }
                }
            }
            '\\' => {
                has_word = true;
                match chars.next() {
                    Some(n) => cur.push(n),
                    None => {
                        return Err(Error::UnbalancedQuote {
                            value: s.to_string(),
                        });
                    }
                }
            }
            c => {
                has_word = true;
                cur.push(c);
            }
        }
    }
    if has_word {
        out.push(cur);
    }
    Ok(out)
}

/// Split `environment:` into defined values and declared-but-undefined keys.
///
/// Compose's bare `- KEY` means "take this from the environment". Via reads it
/// as "this service expects the device to supply KEY", and leaves it for the
/// agent to fill from variables and secrets. Resolving it from the build host
/// instead would bake a developer's shell into the release and give every
/// service the same values whether it wanted them or not.
fn split_environment(v: Option<&MapOrList>) -> (BTreeMap<String, String>, Vec<String>) {
    let mut defined = BTreeMap::new();
    let mut declared = Vec::new();
    match v {
        None => {}
        Some(MapOrList::Map(m)) => {
            for (k, value) in m {
                match value {
                    Some(s) => {
                        defined.insert(k.clone(), s.as_string());
                    }
                    // `KEY:` with no value is the mapping spelling of the same
                    // pass-through form.
                    None => declared.push(k.clone()),
                }
            }
        }
        Some(MapOrList::List(l)) => {
            for item in l {
                match item.split_once('=') {
                    Some((k, value)) => {
                        defined.insert(k.trim().to_string(), value.to_string());
                    }
                    None => declared.push(item.trim().to_string()),
                }
            }
        }
    }
    declared.sort();
    declared.dedup();
    (defined, declared)
}

fn map_or_list_to_map(v: Option<&MapOrList>, sep: char) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    match v {
        None => {}
        Some(MapOrList::Map(m)) => {
            for (k, v) in m {
                // `KEY:` with no value means "inherit from the build
                // environment", which is resolved during interpolation.
                out.insert(
                    k.clone(),
                    v.as_ref().map(|s| s.as_string()).unwrap_or_default(),
                );
            }
        }
        Some(MapOrList::List(l)) => {
            for item in l {
                match item.split_once(sep) {
                    Some((k, v)) => {
                        out.insert(k.trim().to_string(), v.to_string());
                    }
                    None => {
                        let key = item.trim().to_string();
                        let inherited = std::env::var(&key).unwrap_or_default();
                        out.insert(key, inherited);
                    }
                }
            }
        }
    }
    out
}
